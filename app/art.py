def render_satellite_art(
    mode: str = "clean",
    use_color: bool | None = None,
    indent: int = 0,
    trim_blank_rows: bool = True,
) -> str:
    """Render the satellite ASCII art in the requested style.

    Modes:
      - 'clean': Background dots converted to spaces, high-contrast cyan/blue/white gradient.
      - 'stars': Background dots styled as faint deep-space dots, satellite glowing in cyan/blue.
      - 'raw': Verbatim string without color or character changes.
    """
    if use_color is None:
        use_color = sys.stdout.isatty()

    if mode == "raw":
        pad = " " * indent
        return "\n".join(pad + line for line in SATELLITE_ASCII_RAW.strip().splitlines())

    lines = SATELLITE_ASCII_RAW.strip().splitlines()

    if trim_blank_rows:
        start = 0
        while start < len(lines) and set(lines[start]) == {"."}:
            start += 1
        end = len(lines)
        while end > 0 and set(lines[end - 1]) == {"."}:
            end -= 1
        lines = lines[start:end]

    pad = " " * indent
    out: list[str] = []

    for y, line in enumerate(lines):
        # Purple & Yellow cosmic palette
        row_ratio = y / max(1, len(lines) - 1)
        r = int(185 - row_ratio * 40)
        g = int(95 - row_ratio * 45)
        b = int(250 - row_ratio * 25)
        fg = f"\033[38;2;{r};{g};{b}m"
        bold_core = "\033[1;38;2;253;224;71m"
        accent = "\033[38;2;250;204;21m"
        faint_star = "\033[38;2;115;75;155m"
        rst = "\033[0m"

        chars: list[str] = []
        for ch in line:
            if ch == ".":
                if mode == "clean":
                    chars.append(" ")
                elif mode == "stars":
                    chars.append(f"{faint_star}·{rst}" if use_color else ".")
                else:
                    chars.append(".")
            elif ch in "@#%":
                chars.append(f"{bold_core}{ch}{rst}" if use_color else ch)
            elif ch in "*+=":
                chars.append(f"{fg}{ch}{rst}" if use_color else ch)
            else:
                chars.append(f"{accent}{ch}{rst}" if use_color else ch)

        out.append(pad + "".join(chars))

    return "\n".join(out)
